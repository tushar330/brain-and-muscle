import os
import sys
import time
import grpc
import numpy as np

# Generated gRPC files
import topology_pb2
import topology_pb2_grpc

# Add this at the top of ml_worker.py
import importlib.util

def load_user_plugin(file_path):
    if not file_path or not os.path.exists(file_path):
        print(f"[Worker] FATAL: Missing user script at {file_path}")
        sys.exit(1)
    spec = importlib.util.spec_from_file_location("user_model", file_path)
    user_module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(user_module)
    return user_module


# 2MB chunks for safe streaming to prevent Docker OOM kills
CHUNK_SIZE = 2 * 1024 * 1024 

def stream_gradient(worker_id, current_epoch, gradient_matrix):
    """
    Generator function that slices a Numpy array into gRPC TensorChunks.
    """
    print(f"[Worker {worker_id}] Slicing gradient for Epoch {current_epoch}...")
    
    # Flatten and convert to raw bytes
    raw_bytes = gradient_matrix.flatten().astype(np.float32).tobytes()
    total_bytes = len(raw_bytes)
    total_chunks = (total_bytes + CHUNK_SIZE - 1) // CHUNK_SIZE
    
    for i in range(total_chunks):
        start_idx = i * CHUNK_SIZE
        end_idx = min(start_idx + CHUNK_SIZE, total_bytes)
        
        # Yield the chunk to the gRPC network stack
        yield topology_pb2.TensorChunk(
            worker_id=worker_id,
            current_epoch=current_epoch,
            chunk_index=i,
            total_chunks=total_chunks,
            raw_tensor_data=raw_bytes[start_idx:end_idx]
        )

def main():
    chunk_index = os.environ.get("CHUNK_INDEX")
    ps_endpoint = os.environ.get("PS_ENDPOINT")
    user_script = os.environ.get("USER_SCRIPT_PATH") #  NEW
    
    if not chunk_index or not ps_endpoint or not user_script:
        print("[Worker] FATAL: Missing Environment Variables.")
        sys.exit(1)
        
    worker_id = f"worker-{chunk_index}"
    
    #  NEW: Dynamically load the user's math
    user_logic = load_user_plugin(user_script)
    
    print(f"[{worker_id}] Booted up. Connecting to PS at {ps_endpoint}...")

    with grpc.insecure_channel(ps_endpoint) as channel:
        stub = topology_pb2_grpc.ParameterServerStub(channel)
        
        for epoch in range(1, 6):
            print(f"\n[{worker_id}] --- Starting Epoch {epoch} ---")
            
            #  THE FIX: Let the user's plugin do the math!
            # We pass a dummy None for current_weights here to keep it simple, 
            # but in a real system, you'd pull the latest weights from the PS first.
            calculated_gradients = user_logic.compute_gradients(None, chunk_index, epoch)
            
            print(f"[{worker_id}] Streaming gradient to PS...")
            try:
                # Use the gradients generated by the plugin
                response = stub.PushGradients(stream_gradient(worker_id, epoch, calculated_gradients))
                
                if response.success:
                    print(f"[{worker_id}] ✅ PS Acknowledged Epoch {response.acknowledged_epoch}")
                else:
                    print(f"[{worker_id}] ❌ PS rejected the update (Too stale).")
                    
            except grpc.RpcError as e:
                print(f"[{worker_id}] gRPC Network Error: {e.details()}")
                sys.exit(1)

    print(f"\n[{worker_id}] Training complete. Exiting clean.")

if __name__ == '__main__':
    main()